<h1 id="toc0"><span><strong>About This Wiki</strong></span></h1>
<hr />
<p>Welcome to our new Access Technology Florida wiki! This site will enable us to post information, manuals, links, and materials for use by everyone across the state. Why reinvent the wheel? Collaborate to help everyone.</p>
<p>Please send all submissions and suggestions to Eric Barrette at <span class="wiki-email">gro.bohl|etterrabe#gro.bohl|etterrabe</span> or alternatively, feel free to edit the site yourself! Each of you has access to create pages, and add to existing pages. This site does take some getting used to, as it is not quite html code. But feel free to try, I'd like everyone to feel welcome to post to help the group. I've done my best to keep everything in alphabetical order as to make things easy to find and to not show any favoritism to a certain product or dealer.</p>
<p>Be sure to stop by the forum to post comments, questions, or to introduce yourself to the group!</p>
